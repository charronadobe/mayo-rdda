/**
 * Parser for carousel-story.
 * Source: .cmp-slider-from-model (About Mayo Clinic story slider).
 * One row per slide (.cmp-slider__slide), two cells:
 *   image | caption paragraph(s) + <p><a>Read ... story</a></p>
 * Notes on the source:
 *  - Each slide's <picture> has one <source> per breakpoint; the widest file
 *    (2100x900) is used, falling back to the <img> src.
 *  - The whole legend is one link wrapping two paragraphs: caption + "Read ... story".
 *    It is split into the caption paragraph and a link whose text is the last
 *    paragraph (original href).
 *  - Dots / prev-next arrows are removed by the cleanup transformer and are
 *    generated by the block code.
 */
export default function parse(element, { document, params }) {
  const clean = (text) => (text || '').replace(/ /g, ' ').replace(/\s+/g, ' ').trim();

  // widest image among the <source srcset> candidates (file names end in WIDTHxHEIGHT)
  const bestImageSrc = (picture, img) => {
    let best = '';
    let bestWidth = -1;
    if (picture) {
      picture.querySelectorAll('source[srcset]').forEach((source) => {
        source.getAttribute('srcset').split(',').forEach((candidate) => {
          const url = candidate.trim().split(/\s+/)[0];
          if (!url) return;
          const size = url.match(/(\d+)x(\d+)(?=[^/]*$)/);
          const descriptor = candidate.trim().match(/\s(\d+)w$/);
          const width = size ? parseInt(size[1], 10) : (descriptor ? parseInt(descriptor[1], 10) : 0);
          if (width > bestWidth) {
            bestWidth = width;
            best = url;
          }
        });
      });
    }
    return best || (img ? img.getAttribute('src') || '' : '');
  };

  const cells = [];
  element.querySelectorAll('.cmp-slider__slide').forEach((slide) => {
    // Image cell
    const imageCell = [];
    const picture = slide.querySelector('.cmp-media picture, picture');
    const img = (picture && picture.querySelector('img')) || slide.querySelector('img');
    const src = bestImageSrc(picture, img);
    if (src) {
      const image = document.createElement('img');
      image.setAttribute('src', src);
      image.setAttribute('alt', clean(img && img.getAttribute('alt')));
      imageCell.push(image);
    }

    // Caption cell: caption paragraph(s) + story link
    const textCell = [];
    const link = slide.querySelector('a.cmp-slider__legend-link[href], .cmp-slider__legend a[href]');
    const legend = slide.querySelector('.cmp-slider__legend-text') || slide.querySelector('.cmp-slider__legend');
    const paragraphs = legend
      ? [...legend.querySelectorAll('p')].map((p) => clean(p.textContent)).filter(Boolean)
      : [];
    if (!paragraphs.length && legend && clean(legend.textContent)) paragraphs.push(clean(legend.textContent));

    const linkText = paragraphs.length > 1 || link ? paragraphs.pop() || '' : '';
    paragraphs.forEach((text) => {
      const p = document.createElement('p');
      p.textContent = text;
      textCell.push(p);
    });
    if (linkText) {
      const p = document.createElement('p');
      if (link) {
        const a = document.createElement('a');
        a.setAttribute('href', link.getAttribute('href'));
        a.textContent = linkText;
        p.append(a);
      } else {
        p.textContent = linkText;
      }
      textCell.push(p);
    }

    if (!imageCell.length && !textCell.length) return;
    cells.push([imageCell, textCell]);
  });

  const block = WebImporter.Blocks.createBlock(document, { name: 'carousel-story', cells });
  element.replaceWith(block);
}
